import { build } from "esbuild";
import { writeFile, mkdir } from "node:fs/promises";
const result = await build({
  entryPoints: ["viewer/viewer.js"],
  bundle: true,
  minify: true,
  format: "iife",
  write: false,
  legalComments: "inline",
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><style>
*{box-sizing:border-box}body{margin:0;background:#101914;color:#eaf5ed;font:14px -apple-system,sans-serif}#canvas{height:calc(100vh - 108px);touch-action:none}footer{height:108px;padding:10px 14px}button{border:1px solid #365344;background:#20382a;color:#eaf5ed;padding:7px 12px;border-radius:8px;font-size:13px}input[type=range]{width:100%;accent-color:#53ed9c}nav{display:flex;gap:10px;align-items:center;justify-content:space-between}label{font-size:12px}#time{font-variant-numeric:tabular-nums;color:#bac9bd;font-size:12px}small{color:#bac9bd;font-size:11px}</style></head><body><div id="canvas"></div><footer><nav><button id="play">Play</button><span id="time"></span><button id="reset">Reset view</button></nav><input id="scrub" aria-label="Frame" type="range" min="0" max="0" value="0"><nav><label><input id="compare" type="checkbox" checked>Original in blue</label><small>Drag to rotate · Pinch to zoom</small></nav></footer><script>${script}</script></body></html>`;
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/viewerHtml.ts",
  "// Auto-generated by npm run build:viewer. Do not edit.\nexport const viewerHtml = " +
    JSON.stringify(html) +
    ";\n",
);
